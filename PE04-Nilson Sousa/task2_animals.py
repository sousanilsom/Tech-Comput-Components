# List of at least seven different animals
animals = ["lion", "tiger", "elephant", "giraffe", "zebra", "panda", "koala"]

# Use a for loop to print the name of each animal
for animal in animals:
    print(animal)

# Print the first three items in the list using a slice
print("The first three items in the list are:")
print(animals[0:3])

# Print three items from the middle of the list using a slice
print("Three items from the middle of the list are:")
print(animals[2:5])

# Print the last three items in the list using a slice
print("The last three items in the list are:")
print(animals[-3:])
